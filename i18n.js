// ============================================
// i18n Helper Functions
// ============================================

function t(key, lang = null) {
  const currentLang = lang || getLanguage();
  const langDict = translations[currentLang] || translations.en;
  return langDict[key] || translations.en[key] || key;
}

function getLanguage() {
  return localStorage.getItem("ayuthLanguage") || "en";
}

function setLanguage(lang) {
  if (translations[lang]) {
    localStorage.setItem("ayuthLanguage", lang);
    if (typeof appState !== "undefined") {
      appState.language = lang;
    }
    updateUILanguage(lang);

    // If chat only contains greeting or empty, update greeting in new language
    if (typeof appState !== "undefined") {
      const chatMessages = document.getElementById("chatMessages");
      if (chatMessages && appState.conversationHistory.length <= 1) {
        chatMessages.innerHTML = "";
        appState.conversationHistory = [];
        if (typeof addMessageToChat === "function") {
          addMessageToChat(t("greetingMessage"), "assistant");
        }
      }
    }

    // Refresh KB and Profile Summary if active
    if (typeof renderKnowledgeBase === "function") {
      renderKnowledgeBase();
    }
    if (typeof displayInventionProfileSummary === "function") {
      displayInventionProfileSummary();
    }
  }
}

function updateUILanguage(lang = getLanguage()) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const translation = t(key, lang);
    if (translation) {
      if (el.tagName === "INPUT" && (el.type === "button" || el.type === "submit")) {
        el.value = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  const formFields = {
    chatInput: "chatPlaceholder",
    inventionText: "inventionTextPlaceholder",
    kbSearch: "kbSearch",
    q1: "q1Placeholder",
    q2: "q2Placeholder",
    q3: "q3Placeholder",
  };

  Object.entries(formFields).forEach(([id, key]) => {
    const el = document.getElementById(id);
    if (el) el.placeholder = t(key, lang);
  });

  const selects = {
    q4: {
      0: "q4Placeholder",
      1: "q4No",
      2: "q4YesLimited",
      3: "q4YesPublic",
      4: "q4Other",
    },
    q5: {
      0: "q5Placeholder",
      1: "q5No",
      2: "q5Biological",
      3: "q5TK",
      4: "q5Both",
      5: "q5Other",
    },
  };

  Object.entries(selects).forEach(([selectId, options]) => {
    const select = document.getElementById(selectId);
    if (select) {
      Object.entries(options).forEach(([index, key]) => {
        const option = select.options[index];
        if (option) option.textContent = t(key, lang);
      });
    }
  });

  const langSelect = document.getElementById("languageSelect");
  if (langSelect) langSelect.value = lang;

  const settingsBtn = document.getElementById("settingsBtn");
  const infoBtn = document.getElementById("infoBtn");
  if (settingsBtn) settingsBtn.title = t("settingsTitle", lang);
  if (infoBtn) infoBtn.title = t("infoTitle", lang);

  if (typeof updateSessionInfo === "function") {
    updateSessionInfo();
  }
}

// Initialize language on page load
document.addEventListener("DOMContentLoaded", () => {
  const langSelect = document.getElementById("languageSelect");
  if (langSelect) {
    langSelect.value = getLanguage();
    langSelect.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  }
  updateUILanguage(getLanguage());
});
